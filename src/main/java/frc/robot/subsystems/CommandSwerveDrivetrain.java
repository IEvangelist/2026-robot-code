  /** Tracks a supplied field pose with translation capped at 0.5 m/s on each axis. */
  public Command alignCommand(Supplier<Pose2d> targetPose) {
    posePublisher.accept(targetPose.get());
    alignAngleRequest.HeadingController.setP(Constants.AutoConstants.THETA_P);
    alignAngleRequest.HeadingController.setTolerance(
        Units.degreesToRadians(0.5), Units.degreesToRadians(0.5));
    xController.setTolerance(.015, .1);
    yController.setTolerance(.015, .1);
    return applyRequest(
            () -> {
              Pose2d currentPose = getState().Pose;
              double xVelocity =
                  Math.clamp(
                      xController.calculate(currentPose.getX(), targetPose.get().getX()),
                      -0.5,
                      0.5);
              double yVelocity =
                  Math.clamp(
                      yController.calculate(currentPose.getY(), targetPose.get().getY()),
                      -0.5,
                      0.5);

              return alignAngleRequest
                  .withTargetDirection(targetPose.get().getRotation())
                  .withVelocityX(xVelocity)
                  .withVelocityY(yVelocity);
            })
        .beforeStarting(
            () -> {
              Pose2d currentPose = getState().Pose;
              xController.reset();
              yController.reset();
            })
        .until(
            () ->
                xController.atSetpoint()
                    && yController.atSetpoint()
                    && alignAngleRequest.HeadingController.atSetpoint());
    // .andThen(this.runOnce(() -> alignAngleRequest.withVelocityX(0).withVelocityY(0)));
  }

  /** Continuously requests zero field-relative velocity; does not finish on its own. */
