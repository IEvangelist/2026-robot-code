  /** Selects or averages camera headings according to visible tags, then updates gyro yaw. */
  public void visionGyroReset() {
    double cameraAngle = 0.0;
    if (backLeftLeftCamera.hasTarget()
        && backLeftBackCamera.hasTarget()
        && backRightCamera.hasTarget()) {
      if (backLeftLeftCamera.getNumberOfTags() >= 2
          && backLeftBackCamera.getNumberOfTags() >= 2
          && backRightCamera.getNumberOfTags() >= 2
          && backLeftLeftCamera.filterOdometry(true)
          && backLeftBackCamera.filterOdometry(true)
          && backRightCamera.filterOdometry(true)) {
        cameraAngle =
            (backLeftLeftCamera.getPose2d().getRotation().getDegrees()
                    + backLeftBackCamera.getPose2d().getRotation().getDegrees()
                    + backRightCamera.getPose2d().getRotation().getDegrees())
                / 3.0;
        visionResetPublisher.accept("visionreset 1");
        // 1 cam has 2 tags others dont
      } else if ((backLeftLeftCamera.getNumberOfTags() < 2 && backRightCamera.getNumberOfTags() < 2)
          && backLeftBackCamera.getNumberOfTags() >= 2
          && backLeftBackCamera.filterOdometry(true)) {
        cameraAngle = backLeftBackCamera.getPose2d().getRotation().getDegrees();
        visionResetPublisher.accept("visionreset 2");

      } else if (backLeftLeftCamera.getNumberOfTags() >= 2
          && (backLeftBackCamera.getNumberOfTags() < 2 && backRightCamera.getNumberOfTags() < 2)
          && backLeftLeftCamera.filterOdometry(true)) {
        cameraAngle = backLeftLeftCamera.getPose2d().getRotation().getDegrees();
        visionResetPublisher.accept("visionreset 3");

      } else if ((backLeftLeftCamera.getNumberOfTags() < 2
              && backLeftBackCamera.getNumberOfTags() < 2)
          && backRightCamera.getNumberOfTags() >= 2
          && backRightCamera.filterOdometry(true)) {
        cameraAngle = backRightCamera.getPose2d().getRotation().getDegrees();
        visionResetPublisher.accept("visionreset 4");
      }
      // 2 cams have 2 tags other doesnt
      else if ((backLeftLeftCamera.getNumberOfTags() >= 2 && backRightCamera.getNumberOfTags() >= 2)
          && backLeftBackCamera.getNumberOfTags() < 2
          && backLeftLeftCamera.filterOdometry(true)
          && backRightCamera.filterOdometry(true)) {
        cameraAngle =
            (backLeftLeftCamera.getPose2d().getRotation().getDegrees()
                    + backRightCamera.getPose2d().getRotation().getDegrees())
                / 2.0;
        visionResetPublisher.accept("visionreset 5");

      } else if ((backLeftLeftCamera.getNumberOfTags() >= 2
              && backLeftBackCamera.getNumberOfTags() >= 2)
          && backRightCamera.getNumberOfTags() < 2
          && backLeftLeftCamera.filterOdometry(true)
          && backLeftBackCamera.filterOdometry(true)) {
        cameraAngle =
            (backLeftBackCamera.getPose2d().getRotation().getDegrees()
                    + backLeftLeftCamera.getPose2d().getRotation().getDegrees())
                / 2.0;
        visionResetPublisher.accept("visionreset 6");

      } else if ((backRightCamera.getNumberOfTags() >= 2
              && backLeftBackCamera.getNumberOfTags() >= 2)
          && backLeftLeftCamera.getNumberOfTags() < 2
          && backLeftBackCamera.filterOdometry(true)
          && backRightCamera.filterOdometry(true)) {
        cameraAngle =
            (backLeftBackCamera.getPose2d().getRotation().getDegrees()
                    + backRightCamera.getPose2d().getRotation().getDegrees())
                / 2.0;
        visionResetPublisher.accept("visionreset 7");
      } else if (backLeftLeftCamera.getNumberOfTags() < 2
          && backLeftBackCamera.getNumberOfTags() < 2
          && backRightCamera.getNumberOfTags() < 2
          && backLeftLeftCamera.filterOdometry(true)
          && backLeftBackCamera.filterOdometry(true)
          && backRightCamera.filterOdometry(true)) {
        cameraAngle =
            (backLeftLeftCamera.getPose2d().getRotation().getDegrees()
                    + backLeftBackCamera.getPose2d().getRotation().getDegrees()
                    + backRightCamera.getPose2d().getRotation().getDegrees())
                / 3.0;
        visionResetPublisher.accept("visionreset 8");
      }
    } else if (backLeftLeftCamera.hasTarget()
        && (!backLeftBackCamera.hasTarget() && !backRightCamera.hasTarget())
        && backLeftLeftCamera.filterOdometry(true)) {
      cameraAngle = backLeftLeftCamera.getPose2d().getRotation().getDegrees();
      visionResetPublisher.accept("visionreset 9");
    } else if ((!backLeftLeftCamera.hasTarget() && !backRightCamera.hasTarget())
        && backLeftBackCamera.hasTarget()
        && backLeftBackCamera.filterOdometry(true)) {
      cameraAngle = backLeftBackCamera.getPose2d().getRotation().getDegrees();
      visionResetPublisher.accept("visionreset 10");
    } else if ((!backLeftLeftCamera.hasTarget() && !backLeftBackCamera.hasTarget())
        && backRightCamera.hasTarget()
        && backRightCamera.filterOdometry(true)) {
      cameraAngle = backRightCamera.getPose2d().getRotation().getDegrees();
      visionResetPublisher.accept("visionreset 11");
    } else if (!backLeftLeftCamera.hasTarget()
        && backLeftBackCamera.hasTarget()
        && backRightCamera.hasTarget()
        && backLeftBackCamera.filterOdometry(true)
        && backRightCamera.filterOdometry(true)) {
      cameraAngle =
          (backLeftBackCamera.getPose2d().getRotation().getDegrees()
                  + backRightCamera.getPose2d().getRotation().getDegrees())
              / 2.0;
      visionResetPublisher.accept("visionreset 12");
    } else if (backLeftLeftCamera.hasTarget()
        && !backLeftBackCamera.hasTarget()
        && backRightCamera.hasTarget()
        && backLeftLeftCamera.filterOdometry(true)
        && backRightCamera.filterOdometry(true)) {
      cameraAngle =
          (backLeftLeftCamera.getPose2d().getRotation().getDegrees()
                  + backRightCamera.getPose2d().getRotation().getDegrees())
              / 2.0;
      visionResetPublisher.accept("visionreset 13");
    } else if (backLeftLeftCamera.hasTarget()
        && backLeftBackCamera.hasTarget()
        && !backRightCamera.hasTarget()
        && backLeftLeftCamera.filterOdometry(true)
        && backLeftBackCamera.filterOdometry(true)) {
      cameraAngle =
          (backLeftBackCamera.getPose2d().getRotation().getDegrees()
                  + backLeftLeftCamera.getPose2d().getRotation().getDegrees())
              / 2.0;
      visionResetPublisher.accept("visionreset 14");
    }

    if (!backLeftLeftCamera.hasTarget()
        && !backLeftBackCamera.hasTarget()
        && !backRightCamera.hasTarget()
        && backLeftLeftCamera.filterOdometry(true) != true
        && backLeftBackCamera.filterOdometry(true) != true
        && backRightCamera.filterOdometry(true) != true) {
      cameraAngle = getPigeon2().getYaw().getValueAsDouble();
      visionResetPublisher.accept("visionreset 15");
    }
    getPigeon2().setYaw(cameraAngle);
  }

